"""Generate vectorspace_mock.cjs: a mock of /api/v1 that answers with the collection's recorded examples.

The current Postman app has no "mock collection" on the free plan. Its local mocks are a JavaScript
file instead, so this script writes one from the saved examples in vectorspace.postman_collection.json.
Paste the output into a Postman local mock (Mocks → the mock → default scenario) and press Start. It is
plain Node too, so `node vectorspace_mock.cjs` serves the same answers without Postman.

Matching: method + path. A UUID segment matches any id, and the visit slug matches any slug, so
GET /api/v1/projects/<any id> gets the recorded project. Query strings are ignored. Anything else
answers 404 in the API's own error shape, listing the routes the mock knows.

Run from VectorSpace/:  apps/api/.venv/Scripts/python apps/api/postman/build_mock.py
Rerun after build_collection.py so the mock follows the collection.
"""

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
UUID = re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")
SLUG = re.compile(r"^lesson-[0-9a-f]+$")


def walk(items):
    for item in items:
        if "item" in item:
            yield from walk(item["item"])
        else:
            yield item


def pattern(path: str) -> tuple[str, str]:
    """('/api/v1/projects/:id', '^/api/v1/projects/[^/]+$') for a recorded path."""
    shown, regex = [], []
    for seg in path.strip("/").split("/"):
        if UUID.match(seg):
            shown.append(":id")
            regex.append("[^/]+")
        elif SLUG.match(seg):
            shown.append(":slug")
            regex.append("[^/]+")
        else:
            shown.append(seg)
            regex.append(re.escape(seg))
    return "/" + "/".join(shown), "^/" + "/".join(regex) + "/?$"


def main() -> None:
    collection = json.loads((HERE / "vectorspace.postman_collection.json").read_text(encoding="utf-8"))
    routes, seen = [], set()
    for request in walk(collection["item"]):
        for example in request.get("response", []):
            original = example["originalRequest"]
            method = original["method"]
            path = original["url"]["raw"].replace("{{baseUrl}}", "").split("?")[0]
            shown, regex = pattern(path)
            if (method, shown) in seen:
                continue
            seen.add((method, shown))
            body = example.get("body") or ""
            routes.append({
                "method": method,
                "path": shown,
                "regex": regex,
                "status": example["code"],
                "body": json.loads(body) if body.strip() else None,
                "from": request["name"],
            })

    # most literal segments first, so /projects/:id/versions never loses to a looser pattern
    routes.sort(key=lambda r: (-r["path"].count("/"), r["path"].count(":")))

    endpoints = "\n".join(f" * @endpoint {r['method']} {r['path']}" for r in routes)
    table = ",\n".join(
        "  { method: %s, re: /%s/, path: %s, status: %d, body: %s }" % (
            json.dumps(r["method"]), r["regex"].replace("/", "\\/"), json.dumps(r["path"]),
            r["status"], json.dumps(r["body"], ensure_ascii=False),
        )
        for r in routes
    )
    js = f"""/**
 * VectorSpace API v1 mock. GENERATED by apps/api/postman/build_mock.py from the {len(routes)} recorded
 * examples in vectorspace.postman_collection.json; edit the collection, not this file.
 * The data is synthetic (the seeded Demo School). Any id in a path matches; query strings are ignored.
 *
{endpoints}
 */
const http = require("http");
const PORT = process.env.PORT || 4500;
const JSON_HEADER = {{ "Content-Type": "application/json", "X-Mock": "vectorspace" }};

const ROUTES = [
{table}
];

const server = http.createServer((req, res) => {{
  const path = req.url.split("?")[0];
  const route = ROUTES.find((r) => r.method === req.method && r.re.test(path));
  if (!route) {{
    res.writeHead(404, JSON_HEADER);
    return res.end(JSON.stringify({{
      detail: `The mock has no recorded example for ${{req.method}} ${{path}}`,
      routes: ROUTES.map((r) => `${{r.method}} ${{r.path}}`),
    }}));
  }}
  if (route.body === null) {{
    res.writeHead(route.status);
    return res.end();
  }}
  const headers = {{ ...JSON_HEADER }};
  if (Array.isArray(route.body)) headers["X-Total-Count"] = String(route.body.length);
  res.writeHead(route.status, headers);
  res.end(JSON.stringify(route.body, null, 2));
}});

server.listen(PORT, () => console.log(`VectorSpace mock on http://localhost:${{PORT}}/api/v1/health`));
"""
    (HERE / "vectorspace_mock.cjs").write_text(js, encoding="utf-8")
    print(f"vectorspace_mock.cjs: {len(routes)} routes")


if __name__ == "__main__":
    main()
